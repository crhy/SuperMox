#!/usr/bin/env bash
# Behavioural test for init.d/supermox-corosync (task f34: the single-node
# corosync.conf must describe the node that boots, never the machine an ISO
# was built on).
#
# What this guards:
#   * the corosync package's placeholder (name: node1) is replaced by a
#     single-node config naming `hostname` at its first non-loopback address,
#     carrying the header pve-cluster's postinst writes, so both writers
#     recognise each other's output;
#   * a missing file is created;
#   * re-running with the same host and address changes nothing (idempotent);
#   * a moved DHCP address or a renamed node rewrites the one node block;
#   * a real multi-node config is never touched;
#   * a cluster config supermox-join wrote (overlay address, managed header)
#     is never touched either, and `status` accepts its fdXX: address;
#   * no non-loopback address: exit 0 (boot must not be blocked), file untouched;
#   * `status` is LSB 0 when the config maps this node to a non-loopback address
#     and LSB 3 when it is still the placeholder or only maps to loopback;
#   * `stop` never deletes the config;
#   * the LSB headers put this script after /etc/hosts and before corosync and
#     pve-cluster, so the ordering the boot depends on cannot silently regress.
#
# `hostname` is stubbed through PATH and the config is a temp file under build/.
# No root, no network, no real /etc/corosync.
set -euo pipefail

cd "$(dirname "$0")/.."

src="init.d/supermox-corosync"
if [ ! -f "$src" ]; then
  echo "FAIL: $src does not exist"
  exit 1
fi

tmp="$(pwd)/build/test-init-corosync.tmp"
rm -rf "$tmp"
mkdir -p "$tmp/bin" "$tmp/state"

# hostname: the node's name; `hostname -I`: its addresses, from the state dir.
cat > "$tmp/bin/hostname" <<'EOF'
#!/bin/sh
state="${COROSYNC_STATE_DIR:?}"
if [ "${1:-}" = "-I" ]; then
  cat "$state/ips" 2>/dev/null || exit 1
  exit 0
fi
cat "$state/hostname"
EOF
chmod +x "$tmp/bin/hostname"

printf 'myhost\n' > "$tmp/state/hostname"
printf '10.0.2.15 127.0.0.1 \n' > "$tmp/state/ips"

export COROSYNC_STATE_DIR="$tmp/state"
export PATH="$tmp/bin:$PATH"

conf="$tmp/etc/corosync/corosync.conf"
export CONF_FILE="$conf"

mkdir -p "$tmp/etc/corosync"

run() { sh "$src" "${1:-start}"; }

fail=0

# The Debian corosync package's own placeholder, abbreviated.
placeholder() {
  cat > "$conf" <<'EOF'
# Please read the corosync.conf.5 manual page
totem {
	version: 2
	cluster_name: debian
}
nodelist {
	node {
		name: node1
		nodeid: 1
		ring0_addr: 127.0.0.1
	}
}
EOF
}

# --- case 1: placeholder replaced by a single-node config for this node ----
placeholder
if ! run start; then
  echo "FAIL: start exited non-zero on the corosync package placeholder"
  fail=1
fi
for want in \
  '# generated by pve-cluster for single-node SuperMox' \
  'name: myhost' \
  'quorum_votes: 1' \
  'ring0_addr: 10.0.2.15' \
  'provider: corosync_votequorum' \
  'bindnetaddr: 10.0.2.15' \
  'secauth: off'; do
  if ! grep -qF "$want" "$conf"; then
    echo "FAIL: generated config missing: $want"
    fail=1
  fi
done
if grep -q 'node1' "$conf"; then
  echo "FAIL: placeholder node survived in the generated config"
  fail=1
fi
if [ "$(grep -c '^[[:space:]]*name:' "$conf")" != 1 ]; then
  echo "FAIL: $(grep -c '^[[:space:]]*name:' "$conf") node name lines, expected exactly one node"
  fail=1
fi
if [ "$(stat -c '%a' "$conf")" != 644 ]; then
  echo "FAIL: config mode is $(stat -c '%a' "$conf"), expected 644"
  fail=1
fi
if [ -e "$conf.supermox-tmp" ]; then
  echo "FAIL: temp file left behind"
  fail=1
fi

# --- case 2: idempotent --------------------------------------------------
cp "$conf" "$conf.before"
if ! run start; then
  echo "FAIL: start exited non-zero on the second run"
  fail=1
fi
if ! cmp -s "$conf" "$conf.before"; then
  echo "FAIL: second run rewrote an already correct config"
  fail=1
fi

# --- case 3: status is LSB 0 with the mapping in place -------------------
if ! run status; then
  echo "FAIL: status exited non-zero while the config names this node"
  fail=1
fi

# --- case 4: DHCP moved the address -> one node block, new address ------
printf '10.0.2.77 127.0.0.1 \n' > "$tmp/state/ips"
if ! run start; then
  echo "FAIL: start exited non-zero after the address changed"
  fail=1
fi
if [ "$(grep -c '^[[:space:]]*name:' "$conf")" != 1 ]; then
  echo "FAIL: $(grep -c '^[[:space:]]*name:' "$conf") node name lines after an address change"
  fail=1
fi
if ! grep -q 'ring0_addr: 10.0.2.77' "$conf" || ! grep -q 'bindnetaddr: 10.0.2.77' "$conf"; then
  echo "FAIL: config still names the old address after a DHCP change"
  fail=1
fi

# --- case 5: the node was renamed -> the block follows the hostname ------
printf 'pve01\n' > "$tmp/state/hostname"
if ! run start; then
  echo "FAIL: start exited non-zero after the hostname changed"
  fail=1
fi
if ! grep -q 'name: pve01' "$conf"; then
  echo "FAIL: config does not name the current hostname"
  fail=1
fi

# --- case 6: a missing file is created ----------------------------------
rm -f "$conf"
if ! run start; then
  echo "FAIL: start exited non-zero with no corosync.conf at all"
  fail=1
fi
if [ ! -f "$conf" ]; then
  echo "FAIL: no corosync.conf written when the file was missing"
  fail=1
fi

# --- case 7: a real multi-node config is never touched -----------------
cat > "$conf" <<'EOF'
# generated by pvecm create
nodelist {
    node {
        name: pve01
        nodeid: 1
        ring0_addr: 10.0.2.15
    }
    node {
        name: pve02
        nodeid: 2
        ring0_addr: 10.0.2.16
    }
}
EOF
cp "$conf" "$conf.before"
if ! run start; then
  echo "FAIL: start exited non-zero on a multi-node config"
  fail=1
fi
if ! cmp -s "$conf" "$conf.before"; then
  echo "FAIL: multi-node config was rewritten"
  fail=1
fi

# --- case 7b: a cluster config supermox-join wrote is left alone ----------
# Its node is named after the node and addressed by its overlay, which is
# not one of `hostname -I`; rewriting it would drop the cluster.
printf 'myhost\n' > "$tmp/state/hostname"
cat > "$conf" <<EOF
# SuperMox cluster (managed by supermox-join; do not let supermox-corosync rewrite)
totem {
    cluster_name: smx-620d95dc
    config_version: 2
    ip_version: ipv6
    secauth: on
    version: 2
    link_mode: passive
}
nodelist {
    node {
        name: myhost
        nodeid: 1
        quorum_votes: 1
        ring0_addr: fd21:3129:3360:3507:d958:db0e:fba9:0
    }
}
quorum {
    provider: corosync_votequorum
    two_node: 1
}
EOF
cp "$conf" "$conf.before"
if ! run start; then
  echo "FAIL: start exited non-zero on a SuperMox cluster config"
  fail=1
fi
if ! cmp -s "$conf" "$conf.before"; then
  echo "FAIL: the SuperMox cluster config was rewritten"
  fail=1
fi
if ! run status; then
  echo "FAIL: status exited non-zero for a cluster config whose node is this host at its overlay address"
  fail=1
fi

# --- case 8: no non-loopback address -> exit 0, file untouched ----------
placeholder
cp "$conf" "$conf.before"
printf '127.0.0.1 \n' > "$tmp/state/ips"
if ! run start; then
  echo "FAIL: start exited non-zero with only a loopback address (must not block boot)"
  fail=1
fi
if ! cmp -s "$conf" "$conf.before"; then
  echo "FAIL: config rewritten although no usable address exists"
  fail=1
fi
rc=0
run status >/dev/null 2>&1 || rc=$?
if [ "$rc" != 3 ]; then
  echo "FAIL: status exit code is $rc, expected LSB 3 while the config is still the placeholder"
  fail=1
fi

# --- case 9: our own config that maps the node to loopback -> LSB 3 ----
cat > "$conf" <<'EOF'
# generated by pve-cluster for single-node SuperMox
nodelist {
    node {
        name: pve01
        nodeid: 1
        quorum_votes: 1
        ring0_addr: 127.0.0.1
    }
}
EOF
rc=0
run status >/dev/null 2>&1 || rc=$?
if [ "$rc" != 3 ]; then
  echo "FAIL: status exit code is $rc, expected LSB 3 for a loopback mapping"
  fail=1
fi

# --- case 10: stop never deletes the config ---------------------------
if ! run stop; then
  echo "FAIL: stop exited non-zero"
  fail=1
fi
if [ ! -f "$conf" ]; then
  echo "FAIL: stop deleted corosync.conf"
  fail=1
fi

# --- case 11: an unknown action is a usage error ----------------------
rc=0
run bogus >/dev/null 2>&1 || rc=$?
if [ "$rc" = 0 ]; then
  echo "FAIL: unknown action exited 0"
  fail=1
fi

# --- case 12: the LSB headers fix the boot order -------------------
# supermox-hosts must run first (it puts this node's address in /etc/hosts),
# this script must run before corosync starts and before pve-cluster, and the
# pve-cluster package's own init script must wait for us (that dependency ships
# in the patch, since upstream's script is not in this tree).
lsb_src="init.d/supermox-corosync"
lsb_hosts="init.d/supermox-hosts"
lsb_pve="init.d/pve-cluster"
for want in "^# Provides: *supermox-corosync$" \
            '^# Required-Start:.* supermox-hosts' \
            '^# X-Start-Before: *corosync pve-cluster' \
            '^# Default-Start: *2 3 4 5' \
            '^# Default-Stop: *0 1 6'; do
  if ! grep -qE "$want" "$lsb_src"; then
    echo "FAIL: $lsb_src LSB header is missing: $want"
    fail=1
  fi
done
if ! grep -qE '^# X-Start-Before:.*supermox-corosync' "$lsb_hosts"; then
  echo "FAIL: $lsb_hosts does not start supermox-corosync before it"
  fail=1
fi
if ! grep -qE '^# Required-Start:.*corosync supermox-corosync' "$lsb_pve"; then
  echo "FAIL: $lsb_pve does not require supermox-corosync, so pmxcfs could start before its config exists"
  fail=1
fi

# pve-cluster's postinst skips writing corosync.conf in a build chroot. Run its
# in_build_chroot() from patch 0011 on this host, which is not a chroot: it must
# say "not a chroot", or a real node's install would skip the config and an
# image build would bake the build machine's identity in again.
chroot_fn="$(sed -n '/^+in_build_chroot() {$/,/^+}$/s/^+//p' patches/pve-cluster/0011-corosync-conf-at-boot.patch)"
if [ -z "$chroot_fn" ]; then
  echo "FAIL: in_build_chroot() not found in patches/pve-cluster/0011-corosync-conf-at-boot.patch"
  fail=1
elif ! stat -c %d:%i /proc/1/root/. >/dev/null 2>&1; then
  echo "NOTE: /proc/1/root is root-only here; in_build_chroot() not exercised (dpkg runs the postinst as root)"
elif (eval "$chroot_fn"; in_build_chroot); then
  echo "FAIL: in_build_chroot() reports a build chroot on a booted host (inverted test)"
  fail=1
fi

rm -rf "$tmp"

if [ "$fail" -ne 0 ]; then
  exit 1
fi
echo "OK: init.d/supermox-corosync writes a single-node corosync.conf for the node that boots, and the LSB headers order it after /etc/hosts and before corosync and pve-cluster"
