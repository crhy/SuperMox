"""Turn the first node into a real corosync cluster on its overlay address.

Task c06.  Everything here was measured in the amd64 test VM (Debian Ceres,
corosync 3.1.10, pve-cluster from the PXVIRT fork) rather than copied from
upstream, because upstream's cluster-create path is systemd-bound and because
pmxcfs's write rules are not obvious.

Measured facts this module is built on:

* ``/etc/pve`` is a FUSE mount served by pmxcfs, and its files are writable
  only while the cluster is QUORATE.  ``cfs-plug-memdb.c`` reports every
  regular file as ``0666`` when quorate and ``0444`` when not, the mount
  uses ``default_permissions`` (checked in userspace by FUSE, so the missing
  write bit stops root as well), and pmxcfs masks the mode to ``0777750``.
  Measured: before corosync runs, ``open('/etc/pve/corosync.conf', 'w')`` is
  EACCES; once ``corosync-quorumtool -s`` says ``Quorate: Yes`` the same
  write succeeds.  The order of operations is therefore fixed.
* pmxcfs's own copy of the nodelist is the source of truth for PVE
  (``pvecm status`` reads it) and pmxcfs writes it OUT to
  /etc/corosync/corosync.conf (``dcdb_sync_corosync_conf``, mode 0644).
  The import direction host -> database happens only when the database
  file is being created, so writing the host file alone never reaches PVE:
  measured, a host file with a new cluster_id left the PVE copy stale
  forever.  Both copies have to be written.
* pmxcfs refuses to overwrite a NEWER host file ("local corosync.conf
  is newer"), comparing ``config_version``.  Bumping past both copies
  keeps our config from being clobbered at the next pmxcfs start.
* ``state.identity`` keeps ``wg_pub`` as raw bytes while ``membership.json``
  keeps it as base64 text (``state._b64``), so matching this node to its own
  membership entry has to normalise both sides; comparing them raw never
  matches and the node concludes it is not in its own cluster.
* corosync identifies the local host by ADDRESS, not by name: a nodelist
  entry whose ``ring0_addr`` is the local wg0 address is ``(local)`` even
  when ``name`` is not the hostname (measured with ``corosync -t`` and
  ``pvecm status``).  The name is still the hostname, because that is
  what upstream's cluster create does and what PVE keys /etc/pve/nodes/
  by.
* IPv4 addresses cannot work: the overlay hands out IPv6 ULA (fdXX::)
  addresses, which have no IPv4 form, and a config naming a non-local
  address makes corosync exit at start.  ``ip_version: ipv6`` and
  ``secauth: on`` are mandatory.
* ``two_node: 1`` is accepted by corosync 3.1.10 for a two-node cluster
  (``corosync -t`` rc 0); it is what keeps a 2-node cluster from needing
  2/3 of the votes.
* ``corosync -t -c <file>`` validates a config (rc 0 good, rc 8 bad), and
  ``corosync-quorumtool -s`` is the authoritative quorum check -- the
  init script's exit code is not.
* The auth key is /etc/corosync/authkey, mode 0400, generated by
  ``corosync-keygen``; corosync refuses to start without it.
* ``wg up`` returns before the kernel has given the interface its address,
  and corosync dials the address at start instead of waiting for it, so
  the address has to be waited for before the nodelist is written.

The runner is injectable (``run(argv) -> (rc, output)``) so the unit tests
can drive this without a cluster.

Known limitation, for the multi-node tasks: other members are named in
this nodelist by their membership name, which is not necessarily their
hostname.  PVE ssh's to a remote node by that name, so the join protocol
has to carry each node's hostname before multi-node clusters can be
fully managed; see docs/cluster-core-join.md.
"""

import base64
import binascii
import os
import re
import socket
import subprocess
import time

COROSYNC_CONF = "/etc/corosync/corosync.conf"
PVE_COROSYNC_CONF = "/etc/pve/corosync.conf"
PVE_DIR = "/etc/pve"
AUTHKEY = "/etc/corosync/authkey"
MANAGED_MARKER = "# SuperMox cluster (managed by supermox-join"
CLUSTER_NAME_RE = re.compile(r"^smx-[a-z0-9]{8,16}\Z")
# corosync's own rule for a cluster name, and the one `supermox-join create
# --name` enforces before it generates anything.
COROSYNC_NAME_RE = re.compile(r"^[a-zA-Z0-9]([a-zA-Z0-9\-]*[a-zA-Z0-9])?\Z")


def name_ok(name: str) -> bool:
    """True if corosync would accept `name` as a cluster name."""
    return bool(name) and len(name) <= 30 and bool(COROSYNC_NAME_RE.match(name))
# corosync's own node-name rule, as used by upstream's config parser.
NODE_NAME_RE = re.compile(r"^[a-zA-Z0-9]([a-zA-Z0-9\-]*[a-zA-Z0-9])?\Z")
OVERLAY_WAIT_SECONDS = 15
QUORUM_WAIT_SECONDS = 15


class CorosyncError(RuntimeError):
    pass


def default_run(argv):
    """The runner used when the caller does not inject one."""
    proc = subprocess.run(argv, stdout=subprocess.PIPE,
                          stderr=subprocess.STDOUT, text=True)
    return proc.returncode, proc.stdout


def cluster_name(state):
    """The corosync cluster name, derived from the cluster id.

    8 hex characters: corosync's own name rule is short and the id is
    16 bytes, so a prefix plus a slice is enough to stay unique among
    clusters a node might ever see.
    """
    try:
        cid = state.derived["cluster_id"]
    except (AttributeError, KeyError, TypeError):
        cid = b""
    name = "smx-" + binascii.hexlify(cid)[:8].decode("ascii")
    if not CLUSTER_NAME_RE.match(name):
        raise CorosyncError("bad cluster_id %r" % cid)
    return name


def wg_pub_bytes(value):
    """A WireGuard public key as bytes, however the caller stores it.

    state.identity holds raw bytes; membership.json holds base64 text. A
    comparison that does not normalise both sides fails, and the node decides
    it is not a member of the cluster it just created.
    """
    if isinstance(value, bytes):
        return value
    try:
        return base64.b64decode(value, validate=True)
    except (binascii.Error, ValueError, TypeError):
        return b""


def my_entry(state):
    """This node's membership entry, matched on its own WireGuard public key."""
    try:
        wg_pub = wg_pub_bytes(state.identity["wg_pub"])
    except (AttributeError, KeyError, TypeError):
        wg_pub = b""
    if not wg_pub:
        raise CorosyncError("this node has no WireGuard identity")
    for member in getattr(state, "membership", []) or []:
        if wg_pub_bytes(member.get("wg_pub")) == wg_pub:
            return member
    raise CorosyncError("this node is not in the membership list")


def overlay_addr(state):
    addr = my_entry(state).get("overlay_addr", "")
    if not addr:
        raise CorosyncError("no overlay address recorded for this node")
    return addr


def node_name(state):
    """The corosync node name for this node: its hostname.

    PVE keys /etc/pve/nodes/ by hostname and upstream's cluster create
    names nodes the same way, so the nodelist entry for this node has to
    carry the hostname even though corosync itself matches on the address.
    """
    return sanitise_node_name(socket.gethostname())


def sanitise_node_name(raw):
    name = re.sub(r"[^a-zA-Z0-9\-]", "-", raw).strip("-")
    name = name[:15].strip("-")
    if not name or not NODE_NAME_RE.match(name):
        raise CorosyncError("hostname %r is not a usable corosync node name"
                            % raw)
    return name


def render_conf(state, name, config_version, votes=1):
    """Render the first corosync config: this node only, nodeid 1.

    Overlay members are NOT corosync members: an edge node never runs corosync
    with this cluster's key, and listing it would make corosync wait for its
    vote, so the node loses quorum and /etc/pve goes read-only. Core members are
    added later by PVE's own addnode (`pvesh create /cluster/config/nodes/...`),
    which assigns their nodeids and keeps them stable.
    """
    cname = cluster_name(state)
    me = my_entry(state)
    if not me:
        raise CorosyncError("cluster has no members")
    members = [me]
    out = [
        "%s; do not let supermox-corosync rewrite)" % MANAGED_MARKER,
        "totem {",
        "    cluster_name: %s" % cname,
        "    config_version: %d" % config_version,
        "    ip_version: ipv6",
        "    secauth: on",
        "    version: 2",
        "    link_mode: passive",
        "}",
        "nodelist {",
    ]
    for index, member in enumerate(members, start=1):
        addr = member.get("overlay_addr", "")
        if not addr:
            raise CorosyncError("member %s has no overlay address"
                                % member.get("name", "?"))
        member_name = name
        if not NODE_NAME_RE.match(member_name):
            raise CorosyncError("member name %r is not a usable corosync "
                                "node name" % member_name)
        out += [
            "    node {",
            "        name: %s" % member_name,
            "        nodeid: %d" % index,
            "        quorum_votes: %d" % votes,
            "        ring0_addr: %s" % addr,
            "    }",
        ]
    out += [
        "}",
        "quorum {",
        "    provider: corosync_votequorum",
        "}",
        "logging {",
        "    to_syslog: yes",
        "}",
    ]
    return "\n".join(out) + "\n"


def read_config_version(path):
    """The config_version of a nodelist, or 0 if there is no readable one."""
    try:
        with open(path) as handle:
            text = handle.read()
    except OSError:
        return 0
    match = re.search(r"^\s*config_version:\s*(\d+)\s*$", text, re.M)
    return int(match.group(1)) if match else 0


def count_nodes(path):
    """How many node { } entries a corosync.conf lists (0 if unreadable)."""
    try:
        with open(path) as handle:
            text = handle.read()
    except OSError:
        return 0
    return len(re.findall(r"^\s*node\s*\{", text, re.M))


def nodelist_names(path):
    """The names of the node { } entries a corosync.conf lists ([] if unreadable).

    A member is a CORE member of this cluster exactly when its name is in this
    list: an overlay member never runs corosync with this cluster's key, so it
    is never listed (see render_conf).
    """
    try:
        with open(path) as handle:
            text = handle.read()
    except OSError:
        return []
    start = re.search(r"^\s*nodelist\s*\{", text, re.M)
    if not start:
        return []
    depth, end = 0, len(text)
    for index in range(start.end() - 1, len(text)):
        if text[index] == "{":
            depth += 1
        elif text[index] == "}":
            depth -= 1
            if depth == 0:
                end = index
                break
    return re.findall(r"^\s*name:\s*(\S+)\s*$", text[start.end():end], re.M)


def is_managed(path):
    """True when the nodelist at path is ours, not someone else's."""
    try:
        with open(path) as handle:
            return MANAGED_MARKER in handle.readline()
    except OSError:
        return False


def ensure_authkey(run):
    """corosync refuses to start without the shared key."""
    if os.path.exists(AUTHKEY):
        return
    run(["corosync-keygen", "-l"])
    if not os.path.exists(AUTHKEY):
        raise CorosyncError("corosync-keygen produced no %s" % AUTHKEY)
    os.chmod(AUTHKEY, 0o400)


def ensure_pmxcfs_mounted(run):
    """PVE's cluster filesystem has to be up before either copy means anything."""
    if os.path.ismount(PVE_DIR):
        return
    run(["/etc/init.d/pve-cluster", "restart"])
    if not os.path.ismount(PVE_DIR):
        raise CorosyncError("pmxcfs is not mounted at %s" % PVE_DIR)


def wait_for_overlay(state, run=default_run, timeout=OVERLAY_WAIT_SECONDS):
    """Wait until the overlay actually carries this node's address.

    Returns (ok, note).  Worth waiting rather than failing fast: without
    this the nodelist names an address that does not exist yet and corosync
    exits at start, behind an init script that reported success.
    """
    try:
        addr = overlay_addr(state)
    except CorosyncError as exc:
        return False, str(exc)
    deadline = time.monotonic() + timeout
    while True:
        rc, out = run(["ip", "-6", "addr", "show", "dev", "wg0"])
        if rc == 0 and addr in out:
            return True, "overlay carries %s" % addr
        if time.monotonic() >= deadline:
            return False, ("wg0 does not carry %s yet (last: %s)"
                           % (addr, out.strip()[:120] or "no output"))
        time.sleep(1)


def write_host_conf(text, run):
    """Write the copy corosync itself reads, atomically, and only if corosync
    accepts it.

    /etc/corosync is a plain directory, so temp + rename is enough here.
    """
    tmp = COROSYNC_CONF + ".new"
    with open(tmp, "w") as handle:
        handle.write(text)
        handle.flush()
    os.chmod(tmp, 0o640)
    rc, out = run(["corosync", "-t", "-c", tmp])
    if rc != 0:
        os.unlink(tmp)
        raise CorosyncError("corosync rejects the config: %s" % out.strip())
    os.replace(tmp, COROSYNC_CONF)


def write_pve_conf(text, run, attempts=6):
    """Write pmxcfs's copy, which is the one PVE reads.

    Only possible while the cluster is quorate (see the module docstring),
    so this runs after corosync is up; the retries cover the window between
    corosync starting and pmxcfs noticing the quorum.
    """
    last = ""
    for _ in range(attempts):
        try:
            with open(PVE_COROSYNC_CONF, "w") as handle:
                handle.write(text)
                handle.flush()
            return
        except OSError as exc:
            last = str(exc)
            time.sleep(1)
    raise CorosyncError(
        "cannot write %s: pmxcfs keeps the cluster filesystem read-only "
        "until the cluster is quorate (%s)" % (PVE_COROSYNC_CONF, last))


def quorate(run):
    rc, out = run(["corosync-quorumtool", "-s"])
    return rc == 0 and re.search(r"^Quorate:\s+Yes\s*$", out, re.M) is not None


def wait_for_quorum(run, timeout=QUORUM_WAIT_SECONDS):
    """Poll for quorum instead of restarting corosync again.

    Measured in the test VM: a restart that succeeds leaves corosync running
    for a fraction of a second before it has formed a membership, and
    corosync-quorumtool reports failure in that window.  Restarting a second
    time because of that raced the first start and left NO corosync daemon
    running at all (corosync-quorumtool then says "Cannot initialize CMAP
    service" forever).  Polling is the only safe shape.
    """
    deadline = time.monotonic() + timeout
    while True:
        if quorate(run):
            return True, "quorate"
        if time.monotonic() >= deadline:
            return False, "corosync did not reach quorum within %d s" % timeout
        time.sleep(1)


def daemon_running(run=default_run):
    """Whether a corosync daemon is up at all, for a useful error message."""
    rc, out = run(["pgrep", "-x", "corosync"])
    return rc == 0 and out.strip() != ""


def init_cluster(state, run=default_run, quorum_wait=QUORUM_WAIT_SECONDS):
    """Make this node a real corosync cluster.

    Idempotent: re-running bumps config_version and re-verifies.  The
    order is forced by pmxcfs: host copy -> corosync -> quorate ->
    database copy -> pve-cluster.  Returns (ok, note).
    """
    try:
        cname = cluster_name(state)
        addr = overlay_addr(state)
        name = node_name(state)

        ensure_pmxcfs_mounted(run)
        ensure_authkey(run)

        nodes = count_nodes(PVE_COROSYNC_CONF)
        if is_managed(PVE_COROSYNC_CONF) and nodes > 1:
            # Core members joined through addnode: rewriting the nodelist
            # with this node alone would throw them out of the cluster.
            return True, ("already a corosync cluster with %d nodes; "
                          "not rewritten" % nodes)
        version = max(read_config_version(COROSYNC_CONF),
                      read_config_version(PVE_COROSYNC_CONF)) + 1
        text = render_conf(state, name=name, config_version=version)

        write_host_conf(text, run)
        run(["/etc/init.d/corosync", "restart"])

        ok, note = wait_for_quorum(run, quorum_wait)
        if not ok:
            if not daemon_running(run):
                raise CorosyncError(
                    "corosync is not running with the new config; the nodelist "
                    "is in %s but PVE was not told about it" % COROSYNC_CONF)
            raise CorosyncError("%s; the nodelist is in %s but PVE was not "
                                "told about it" % (note, COROSYNC_CONF))

        write_pve_conf(text, run)
        run(["/etc/init.d/pve-cluster", "restart"])

        ok, note = wait_for_quorum(run, quorum_wait)
        if not ok:
            raise CorosyncError("cluster lost quorum after restarting "
                                "pve-cluster: %s" % note)
        rc, out = run(["pvecm", "status"])
        if rc != 0 or cname not in out:
            raise CorosyncError(
                "pvecm status does not show cluster %s: %s"
                % (cname, out.strip()[:200]))
        return True, "cluster %s node %s config_version %d quorate" % (
            cname, name, version)
    except CorosyncError as exc:
        return False, str(exc)
