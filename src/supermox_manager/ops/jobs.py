"""Scheduled backup jobs (the cluster's vzdump schedule) and running one now.

Every path and parameter name below was read from the running node with
`pvesh usage` (recorded in .strata/notes-t75-manager-backup-jobs-ha.md); nothing
is guessed. A job's settings are stored with hyphenated names (notes-template,
prune-backups); prune-backups comes back as a hash and travels back to the
server as `keep-all=1,keep-daily=2`.

Endpoints:
  GET    /cluster/backup                    list the jobs
  POST   /cluster/backup                    create a job (id is autogenerated)
  PUT    /cluster/backup/{id}               change one job
  DELETE /cluster/backup/{id}               delete a job
  POST   /nodes/{node}/vzdump               run a job's settings right now
"""

import re

from .. import api

# A schedule is a subset of systemd calendar events ("sun 03:00", "daily",
# "*-*-* 03:00:00", "Mon 22:00"). The server does the real parsing; we only
# refuse an empty string or characters that cannot occur in a schedule at all.
_SCHEDULE_RE = re.compile(r"[0-9a-zA-Z*/:,. -]+")
# A job id is one path segment. Anything else is encoded for the URL, but
# separators that would change the endpoint are refused outright.
_ID_RE = re.compile(r"[^/\x00-\x1f\x7f]+")
_MODES = ("snapshot", "stop", "suspend")


def validate_schedule(value):
    """Return the cleaned schedule string, or raise ValueError.

    This is a cheap sanity check only: the server decides whether the
    calendar expression is really valid.
    """
    value = (value or "").strip()
    if not value:
        raise ValueError("A backup job needs a schedule, for example 'sun 03:00'.")
    if not _SCHEDULE_RE.fullmatch(value):
        raise ValueError(
            "The schedule may only contain letters, digits and "
            "the characters */:,. - (for example 'sun 03:00' or 'daily').")
    return value


def _id(value):
    if not value or not _ID_RE.fullmatch(str(value)):
        raise ValueError("The job name may not be empty and may not contain "
                         "a slash or control characters.")
    return str(value)


def _prune(value):
    """prune-backups travels as 'keep-all=1,keep-daily=2'."""
    if isinstance(value, dict):
        return ",".join("{}={}".format(key, value[key]) for key in sorted(value))
    return value


def _fields(job):
    """Turn a job record into the vzdump parameter set.

    Hyphenated API names become the same hyphenated names the server sent
    them under, so a job can be replayed unchanged.
    """
    params = {}
    for key in ("storage", "mode", "compress", "notes-template",
                "prune-backups", "exclude", "script", "tmpdir", "dumpdir"):
        value = job.get(key)
        if value not in (None, ""):
            params[key] = _prune(value) if key == "prune-backups" else value
    return params


def backup_jobs(client):
    """GET /cluster/backup: the cluster's scheduled backup jobs."""
    return client.request("GET", "/cluster/backup")


def create_backup_job(client, schedule, storage=None, vmid=None, all=False,
                      mode="snapshot", compress=0, enabled=True,
                      notes_template=None, prune_backups=None,
                      comment=None, job_id=None):
    """POST /cluster/backup: create a scheduled backup job.

    ``vmid`` backs up one guest; ``all=True`` backs up every guest on the
    node (the server's own --all). Returns null on success; read the job back
    with backup_jobs() to get its generated id.
    """
    params = {"schedule": validate_schedule(schedule),
              "mode": mode,
              "compress": compress,
              "enabled": 1 if enabled else 0}
    if all:
        params["all"] = 1
    elif vmid is None:
        raise ValueError("Pick a machine to back up, or back up all machines.")
    else:
        params["vmid"] = str(int(vmid))
    if storage:
        params["storage"] = storage
    if notes_template:
        params["notes-template"] = notes_template
    if prune_backups:
        params["prune-backups"] = _prune(prune_backups)
    if comment:
        params["comment"] = comment
    if job_id:
        params["id"] = _id(job_id)
    return client.request("POST", "/cluster/backup", params)


def update_backup_job(client, job_id, **fields):
    """PUT /cluster/backup/{id}: change one job's settings.

    Keyword arguments use the Python spelling of the API names
    (``notes_template``, ``prune_backups``, ``allow_move`` ...); underscores
    become hyphens. A schedule is validated before it is sent.
    """
    params = {}
    for key, value in fields.items():
        name = key.replace("_", "-")
        if name == "schedule":
            value = validate_schedule(value)
        elif name == "prune-backups":
            value = _prune(value)
        elif name == "enabled":
            value = 1 if value else 0
        params[name] = value
    if not params:
        raise ValueError("Nothing to change.")
    return client.request("PUT", "/cluster/backup/{}".format(api.segment(job_id)),
                          params)


def delete_backup_job(client, job_id):
    """DELETE /cluster/backup/{id}: remove a scheduled job."""
    return client.request("DELETE",
                          "/cluster/backup/{}".format(api.segment(_id(job_id))))


def run_now(client, node, job):
    """POST /nodes/{node}/vzdump: run a job's settings right now.

    ``job`` is a job record from backup_jobs(); its storage, mode, compress,
    prune-backups and notes-template are replayed on the node. Returns the
    task UPID, so the caller polls it with ops.tasks.wait_task.
    """
    params = _fields(job)
    if job.get("all"):
        params["all"] = 1
    else:
        vmid = job.get("vmid")
        if not vmid:
            raise ValueError("This job has no machine to back up.")
        params["vmid"] = int(str(vmid).split(",")[0]) if isinstance(vmid, str) else int(vmid)
    if "mode" not in params:
        params["mode"] = "snapshot"
    # SuperMox ships no email/notification system, so a backup must not fail
    # just because the default mail-to-root notification has no recipient.
    # legacy-sendmail only sends when mailto is set, which we never do here.
    if "notification-mode" not in params:
        params["notification-mode"] = "legacy-sendmail"
    return client.request("POST", "/nodes/{}/vzdump".format(api.segment(node)),
                          params)
